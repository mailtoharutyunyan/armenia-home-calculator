// Полное название нормы для показа человеку. Для составных кодов вида
// «A / B» разворачивает обе части. Неизвестный код возвращается как есть.
export function normFull(code: string, lang: string): string {
  return normParts(code)
    .map((m) => (typeof m === 'string' ? m : lang === 'hy' ? m.fullHy : m.fullRu))
    .join(' · ')
}

// Разбирает код предупреждения на отдельные документы. Составной код
// «ГОСТ 31360-2024 / ՀՀՇՆ 20.04-2020» ссылается на два разных текста, поэтому
// каждый должен получить свою ссылку, а не одну общую на всю строку.
export function normParts(code: string): (NormMeta | string)[] {
  return code.split('/').map((part) => NORMS[part.trim()] ?? part.trim())
}

// Ведёт ли ссылка на конкретный акт, а не на корень реестра. Прямые адреса
// содержат идентификатор документа; для остальных честнее сказать «поиск»,
// чем притворяться, что клик откроет нужный текст.
export function isDirectSource(url: string): boolean {
  return /\/acts\/\d+|tid=\d+|projects\/\d+/.test(url)
}

